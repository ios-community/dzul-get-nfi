/// Returns the coordinates for a given TSPLIB dataset name.
///
/// Logic:
/// 1. Check if `datasets/{name}.tsp` exists locally.
/// 2. If not, use hardcoded fallback (small-medium, n <= 442).
/// 3. If no hardcoded coords, try online fetch from TSPLIB mirror.
/// 4. Return `None` for benchmark instances without real TSPLIB coordinates.
///    Synthetic coordinates are only returned via [`get_synthetic_dataset`] when
///    an instance explicitly requests synthetic mode, never as a fallback for
///    TSPLIB benchmark instances with known optimal costs.
#[must_use]
pub fn get_dataset(name: &str) -> Option<Vec<(f64, f64)>> {
    let cache_dir = Path::new("datasets");
    let cache_path = cache_dir.join(format!("{name}.tsp"));

    // 1. Try local cache
    if let Ok(content) = fs::read_to_string(&cache_path)
        && let Some(coords) = parse_tsplib_content(&content)
    {
        return Some(coords);
    }

    // 2. Hardcoded fallback FIRST for known small instances
    let hardcoded = match name {
        "eil51" => Some(EIL51_COORDS.to_vec()),
        "berlin52" => Some(BERLIN52_COORDS.to_vec()),
        "st70" => Some(ST70_COORDS.to_vec()),
        "eil76" => Some(EIL76_COORDS.to_vec()),
        "pr76" => Some(PR76_COORDS.to_vec()),
        "rd100" => Some(RD100_COORDS.to_vec()),
        "lin105" => Some(LIN105_COORDS.to_vec()),
        "kroA100" => Some(KROA100_COORDS.to_vec()),
        "ch150" => Some(CH150_COORDS.to_vec()),
        "rat195" => Some(RAT195_COORDS.to_vec()),
        "kroA200" => Some(KROA200_COORDS.to_vec()),
        "tsp225" => Some(TSP225_COORDS.to_vec()),
        "pr226" => Some(PR226_COORDS.to_vec()),
        "gil262" => Some(GIL262_COORDS.to_vec()),
        "a280" => Some(A280_COORDS.to_vec()),
        "lin318" => Some(LIN318_COORDS.to_vec()),
        "pcb442" => Some(PCB442_COORDS.to_vec()),
        _ => None,
    };
    if let Some(coords) = hardcoded {
        return Some(coords);
    }

    // 3. Try fast GitHub Raw CDN mirror with strict 3-second timeout
    let mirror_url = format!("https://raw.githubusercontent.com/mastqe/tsplib/master/{name}.tsp");
    let agent = ureq::Agent::config_builder()
        .timeout_global(Some(std::time::Duration::from_secs(3)))
        .build()
        .new_agent();

    if let Ok(mut response) = agent.get(&mirror_url).call()
        && let Ok(content) = response.body_mut().read_to_string()
    {
        let _ = fs::create_dir_all(cache_dir);
        if let Ok(mut file) = fs::File::create(&cache_path) {
            let _ = file.write_all(content.as_bytes());
        }
        if let Some(coords) = parse_tsplib_content(&content) {
            return Some(coords);
        }
    }

    // 4. Return None if fetch fails or times out
    None
}

/// Returns synthetic deterministic coordinates for an instance.
///
/// This must ONLY be used when an instance explicitly requests synthetic mode,
/// never as a fallback for TSPLIB benchmark instances with known optimal costs.
/// The synthetic coordinates are reproducible (seeded by the instance name)
/// but will NOT match TSPLIB optimal values.
#[must_use]
pub fn get_synthetic_dataset(name: &str) -> Option<Vec<(f64, f64)>> {
    let n = instance_node_count(name)?;
    Some(generate_synthetic_coords(name, n))
}

/// Returns the expected node count for a known TSPLIB instance name.
